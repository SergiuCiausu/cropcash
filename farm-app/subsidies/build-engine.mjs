/* Bundles the tested subsidy engine and docs/data into engine.js, so the pages open without a server.
   Run after the engine or docs/data change: node farm-app/subsidies/build-engine.mjs
   build.mjs also builds it, together with what the pages need to reach the API. */
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

export const engineOptions = {
  entryPoints: [here('engine-entry.ts')],
  outfile: here('engine.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'CropEngine',
  platform: 'browser',
  charset: 'utf8',
  banner: { js: '/* Generated by build-engine.mjs. Do not edit. */' },
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await build(engineOptions);
