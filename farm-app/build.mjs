/* Builds what the pages load: engine.js, live.js and config.js.
   npm run build:farm   once
   npm run dev:farm     serves farm-app on the port the API already allows, and rebuilds on change
   Both also write sw.js, the service worker that keeps the pages on the phone. */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { context } from 'esbuild';
import { publicConfig } from './live/public-config.mjs';
import { engineOptions } from './subsidies/build-engine.mjs';
import { cacheList, swSource, versionOf } from './live/service-worker.mjs';

const PORT = 5173;
const here = (path) => fileURLToPath(new URL(path, import.meta.url));

try {
  process.loadEnvFile(here('../.env'));
} catch {
  // Hosted builds set these in the environment.
}

const config = publicConfig(process.env);
writeFileSync(
  here('config.js'),
  `/* Generated by build.mjs. Public values only. */\nwindow.CROPCASH_CONFIG = ${JSON.stringify(config)};\n`,
);

const liveOptions = {
  entryPoints: [here('live/index.ts')],
  outfile: here('live.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'Live',
  platform: 'browser',
  charset: 'utf8',
  banner: { js: '/* Generated by build.mjs. Do not edit. */' },
};

const builds = await Promise.all([context(engineOptions), context(liveOptions)]);

/* After the scripts exist, so the list and the version include them. */
function writeServiceWorker() {
  const root = here('.');
  const files = cacheList(root);
  writeFileSync(here('sw.js'), swSource(files, versionOf(root, files)));
}

if (process.argv.includes('--serve')) {
  await Promise.all(builds.map((b) => b.rebuild()));
  writeServiceWorker();
  await Promise.all(builds.map((b) => b.watch()));
  await builds[1].serve({ servedir: here('.'), port: PORT });
  console.log(`farm-app: http://localhost:${PORT}/subsidies/subventii.html`);
} else {
  await Promise.all(builds.map((b) => b.rebuild()));
  await Promise.all(builds.map((b) => b.dispose()));
  writeServiceWorker();
  console.log('farm-app: built engine.js, live.js, config.js and sw.js');
}
