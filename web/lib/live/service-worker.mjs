/* The service worker that lets the farm app open without internet. build.mjs writes it to
   farm-app/sw.js with the list of files to keep, and a version that changes with them. */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const KEEP = /\.(html|js|css|svg|png|jpe?g|webp|ico|woff2?|webmanifest)$/;
const SKIP_DIRS = new Set(['node_modules', 'live']);
const SKIP_FILES = new Set(['sw.js']);

/** Every file the pages can load, as paths from the farm-app folder. */
export function cacheList(root) {
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) {
        if (!SKIP_DIRS.has(name)) walk(path);
      } else if (KEEP.test(name) && !SKIP_FILES.has(name) && !name.endsWith('.mjs')) {
        out.push(relative(root, path).split(sep).join('/'));
      }
    }
  };
  walk(root);
  return out;
}

/** Changes whenever a kept file changes, so the phone picks up the new version. */
export function versionOf(root, files) {
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
  return hash.digest('hex').slice(0, 12);
}

export function swSource(files, version) {
  return `/* Generated by build.mjs. Do not edit. */
const CACHE = 'cropcash-farm-${version}';
const FONTS = 'cropcash-fonts';
const FILES = ${JSON.stringify(files)};
const WAIT_MS = 4000;
/* Photos are nice to have offline. One that fails mustn't cost the farmer the whole offline app. */
const isPhoto = (f) => /\.(jpe?g|webp)$/.test(f);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(FILES.filter((f) => !isPhoto(f))).then(() => Promise.allSettled(FILES.filter(isPhoto).map((f) => cache.add(f)))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cropcash-farm-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/* Pages and scripts: the network first, so a change shows at once; the phone's copy when the
   network is missing, too slow or answers with an error. Fonts never change, so the copy comes first. The API is never
   cached here: the pages keep their own copy of the farm. */
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin && !url.pathname.startsWith('/api/')) event.respondWith(networkFirst(req, url));
  else if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') event.respondWith(cacheFirst(req));
});

async function networkFirst(req, url) {
  const cache = await caches.open(CACHE);
  const key = url.origin + url.pathname;
  const network = fetch(req).then(async (res) => {
    if (!res.ok) return (await cache.match(key)) ?? res;
    cache.put(key, res.clone());
    return res;
  });
  network.catch(() => undefined); // When the phone's copy wins the race, nobody is left waiting on this.
  const slow = new Promise((done) => setTimeout(done, WAIT_MS));
  try {
    const first = await Promise.race([network, slow.then(() => cache.match(key))]);
    if (first) return first;
    return await network;
  } catch (e) {
    return (await cache.match(key)) ?? Response.error();
  }
}

async function cacheFirst(req) {
  const cache = await caches.open(FONTS);
  const hit = await cache.match(req);
  if (hit) return hit;
  try {
    const res = await fetch(req);
    if (res.ok || res.type === 'opaque') cache.put(req, res.clone());
    return res;
  } catch (e) {
    return Response.error(); // Offline with no copy: the page falls back to the phone's own font.
  }
}
`;
}
